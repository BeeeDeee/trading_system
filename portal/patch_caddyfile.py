#!/usr/bin/env python3
"""Rewrite the routing part of the live Caddyfile for the dashboards portal (idempotent).

  patch_caddyfile.py IN OUT      writes the patched config to OUT, exit 0; exit 3 if IN is already patched.

Replaces: `root * /srv/cpb/current`, the research-lab block, the `@allowed ... handle { respond 404 }` routing,
X-Frame-Options DENY and CSP frame-ancestors 'none'. Everything else (tls, basic_auth, log) stays byte for byte.
"""
import re
import sys

ROUTING = """\t# dashboards portal: / = tab shell, /crypto/ /lab/ /evening/ = the dashboards (same origin, iframed by the shell)
\tredir /crypto /crypto/
\tredir /lab /lab/
\tredir /evening /evening/
\tredir /data.json /crypto/data.json
\thandle_path /crypto/* {
\t\troot * /srv/cpb/current
\t\t@cpb path / /index.html /data.json
\t\thandle @cpb {
\t\t\tfile_server
\t\t}
\t\thandle {
\t\t\trespond 404
\t\t}
\t}
\t# research-lab dashboard (static, generated by labcore after every cycle)
\thandle_path /lab/* {
\t\troot * /srv/research-lab/web/current
\t\tfile_server
\t}
\t# evening bot dashboard (static, generated on this server after every run)
\thandle_path /evening/* {
\t\troot * /srv/evening/current
\t\tfile_server
\t}
\t@portal path / /index.html
\thandle @portal {
\t\troot * /srv/portal/current
\t\tfile_server
\t}
\thandle {
\t\trespond 404
\t}
"""


def patch(s):
    if "/srv/portal/current" in s:
        return None
    s, n = re.subn(r"\troot \* /srv/cpb/current\n", "", s, count=1)
    assert n == 1, "root line not found"
    # from the (optional) research-lab block or @allowed, through the final `handle { respond 404 }`
    pat = re.compile(r"(?:\t# research-lab dashboard[^\n]*\n(?:\t[^\n]*\n)*?)?\t@allowed path[^\n]*\n\thandle @allowed \{\n\t\tfile_server\n\t\}\n\thandle \{\n\t\trespond 404\n\t\}\n")
    s, n = pat.subn(lambda m: ROUTING, s, count=1)
    assert n == 1, "routing block not recognised"
    s, n = re.subn(r'X-Frame-Options "DENY"', 'X-Frame-Options "SAMEORIGIN"', s, count=1)
    assert n == 1, "X-Frame-Options not found"
    s, n = re.subn(r"frame-ancestors 'none'\"", "frame-src 'self'; frame-ancestors 'self'\"", s, count=1)
    assert n == 1, "CSP frame-ancestors not found"
    return s


if __name__ == "__main__":
    src = open(sys.argv[1]).read()
    out = patch(src)
    if out is None:
        sys.exit(3)
    open(sys.argv[2], "w").write(out)
